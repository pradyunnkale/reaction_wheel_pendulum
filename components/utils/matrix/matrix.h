static inline void mat4x4_transpose(const float A[4][4], float B[4][4])
{
	// Row 0
	B[0][0] = A[0][0];
	B[0][1] = A[1][0];
	B[0][2] = A[2][0];
	B[0][3] = A[3][0];

	// Row 1
	B[1][0] = A[0][1];
	B[1][1] = A[1][1];
	B[1][2] = A[2][1];
	B[1][3] = A[3][1];

	// Row 2
	B[2][0] = A[0][2];
	B[2][1] = A[1][2];
	B[2][2] = A[2][2];
	B[2][3] = A[3][2];

	// Row 3
	B[3][0] = A[0][3];
	B[3][1] = A[1][3];
	B[3][2] = A[2][3];
	B[3][3] = A[3][3];
}

static inline void mat_mul_4x4_4x4(const float A[4][4], const float B[4][4], float C[4][4])
{
	// Row 0
	C[0][0] = A[0][0]*B[0][0] + A[0][1]*B[1][0] + A[0][2]*B[2][0] + A[0][3]*B[3][0];
	C[0][1] = A[0][0]*B[0][1] + A[0][1]*B[1][1] + A[0][2]*B[2][1] + A[0][3]*B[3][1];
	C[0][2] = A[0][0]*B[0][2] + A[0][1]*B[1][2] + A[0][2]*B[2][2] + A[0][3]*B[3][2];
	C[0][3] = A[0][0]*B[0][3] + A[0][1]*B[1][3] + A[0][2]*B[2][3] + A[0][3]*B[3][3];

	// Row 1
	C[1][0] = A[1][0]*B[0][0] + A[1][1]*B[1][0] + A[1][2]*B[2][0] + A[1][3]*B[3][0];
	C[1][1] = A[1][0]*B[0][1] + A[1][1]*B[1][1] + A[1][2]*B[2][1] + A[1][3]*B[3][1];
	C[1][2] = A[1][0]*B[0][2] + A[1][1]*B[1][2] + A[1][2]*B[2][2] + A[1][3]*B[3][2];
	C[1][3] = A[1][0]*B[0][3] + A[1][1]*B[1][3] + A[1][2]*B[2][3] + A[1][3]*B[3][3];

	// Row 2
	C[2][0] = A[2][0]*B[0][0] + A[2][1]*B[1][0] + A[2][2]*B[2][0] + A[2][3]*B[3][0];
	C[2][1] = A[2][0]*B[0][1] + A[2][1]*B[1][1] + A[2][2]*B[2][1] + A[2][3]*B[3][1];
	C[2][2] = A[2][0]*B[0][2] + A[2][1]*B[1][2] + A[2][2]*B[2][2] + A[2][3]*B[3][2];
	C[2][3] = A[2][0]*B[0][3] + A[2][1]*B[1][3] + A[2][2]*B[2][3] + A[2][3]*B[3][3];

	// Row 3
	C[3][0] = A[3][0]*B[0][0] + A[3][1]*B[1][0] + A[3][2]*B[2][0] + A[3][3]*B[3][0];
	C[3][1] = A[3][0]*B[0][1] + A[3][1]*B[1][1] + A[3][2]*B[2][1] + A[3][3]*B[3][1];
	C[3][2] = A[3][0]*B[0][2] + A[3][1]*B[1][2] + A[3][2]*B[2][2] + A[3][3]*B[3][2];
	C[3][3] = A[3][0]*B[0][3] + A[3][1]*B[1][3] + A[3][2]*B[2][3] + A[3][3]*B[3][3];
}

static inline void mat2x4_transpose(const float A[2][4], float B[4][2])
{
	// Row 0 
	B[0][0] = A[0][0];
	B[0][1] = A[1][0];

	// Row 1
	B[1][0] = A[0][1];
	B[1][1] = A[1][1];

	// Row 2 
	B[2][0] = A[0][2];
	B[2][1] = A[1][2];

	// Row 3 
	B[3][0] = A[0][3];
	B[3][1] = A[1][3];
}

