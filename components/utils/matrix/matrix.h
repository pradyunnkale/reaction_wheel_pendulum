static inline void mat_mul_4x2_2x2(const float A[4][2], const float B[2][2], float C[4][2])
{
	// Row 0
	C[0][0] = A[0][0]*B[0][0] + A[0][1]*B[1][0];
	C[0][1] = A[0][0]*B[0][1] + A[0][1]*B[1][1];

	// Row 1
	C[1][0] = A[1][0]*B[0][0] + A[1][1]*B[1][0];
	C[1][1] = A[1][0]*B[0][1] + A[1][1]*B[1][1];

	// Row 2
	C[2][0] = A[2][0]*B[0][0] + A[2][1]*B[1][0];
	C[2][1] = A[2][0]*B[0][1] + A[2][1]*B[1][1];

	// Row 3
	C[3][0] = A[3][0]*B[0][0] + A[3][1]*B[1][0];
	C[3][1] = A[3][0]*B[0][1] + A[3][1]*B[1][1];
}

static inline void mat_mul_4x2_2x1(const float A[4][2], const float B[2], float C[4])
{
	C[0] = A[0][0]*B[0] + A[0][1] * B[1];
	C[1] = A[1][0]*B[0] + A[1][1] * B[1];
	C[2] = A[2][0]*B[0] + A[2][1] * B[1];
	C[3] = A[3][0]*B[0] + A[3][1] * B[1];
}

